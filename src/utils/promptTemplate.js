export function parseItems(text) {
  return text
    .split('\n')
    .map(l => l.trim())
    .filter(Boolean)
    .map(line => line.replace(/^\d+[、，.．,)\]]\s*/, ''))
    .filter(Boolean)
}

export function buildContentUserPrompt(title, items, perImage, watermark, showIndex, textAlign, extraRequirement) {
  const groups = []
  for (let i = 0; i < items.length; i += perImage) {
    groups.push(items.slice(i, i + perImage))
  }

  let prompt = `主题标题：${title}\n\n`
  prompt += `每张图包含 ${perImage} 个格子。\n\n`
  prompt += '素材内容：\n'
  items.forEach((item, i) => {
    if (showIndex) {
      prompt += `${i + 1}、${item}\n`
    } else {
      prompt += `${item}\n`
    }
  })
  prompt += '\n请为以下分组各生成一段完整的生图提示词：\n'
  groups.forEach((group, gi) => {
    const start = gi * perImage + 1
    const end = start + group.length - 1
    prompt += `第${gi + 1}张图：素材 ${start}-${end}（共${group.length}个格子）\n`
  })

  if (showIndex) {
    prompt += '\n序号要求：每条文字前面必须带序号，如"1、xxx"、"2、xxx"，序号从素材原始编号开始。'
  } else {
    prompt += '\n序号要求：文字前面不要带任何序号或编号，直接写内容文字。'
  }

  if (textAlign === 'center') {
    prompt += '\n对齐方式：文字区域的文字必须水平居中对齐，不要左对齐。'
  } else {
    prompt += '\n对齐方式：严格左对齐，左侧留出格子宽度5%的边距。'
  }

  if (watermark) {
    prompt += `\n水印要求：全图右下角位置用醒目的红字标注：${watermark}`
  } else {
    prompt += '\n不需要水印，不要在画面中添加任何署名或水印文字。'
  }

  if (extraRequirement && extraRequirement.trim()) {
    prompt += `\n\n用户补充要求:${extraRequirement.trim()}`
  }

  return prompt
}

